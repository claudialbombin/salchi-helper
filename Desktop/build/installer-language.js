/**
 * @file Generates the NSIS script that adds a language menu to the Windows installer.
 *
 * The installer shows a drop-down with every language Salchi speaks, written in that
 * language, with the one Windows uses already selected. The choice is saved to
 * `resources/install-language.txt`, which the app reads on its first start (see
 * `adoptInstallerLanguage` in src/main/main.js), so it opens directly in that language.
 *
 * The script is generated from the shared `locales` folder so the list of languages and the
 * menu's own text never get out of step with the app.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const LOCALES = path.join(__dirname, '..', '..', 'locales');

/**
 * Windows primary language IDs (the low 10 bits of an LCID) for each Salchi language.
 * Languages with regional variants are resolved from the full LCID in `REGIONAL`.
 */
const PRIMARY = {
  ar: 0x01, bg: 0x02, ca: 0x03, cs: 0x05, da: 0x06, de: 0x07, el: 0x08, es: 0x0a, fi: 0x0b,
  fr: 0x0c, he: 0x0d, hu: 0x0e, it: 0x10, ja: 0x11, ko: 0x12, nl: 0x13, nb: 0x14, pl: 0x15,
  ro: 0x18, ru: 0x19, hr: 0x1a, sk: 0x1b, sv: 0x1d, th: 0x1e, tr: 0x1f, ur: 0x20, id: 0x21,
  uk: 0x22, sl: 0x24, et: 0x25, lv: 0x26, lt: 0x27, fa: 0x29, vi: 0x2a, eu: 0x2d, hi: 0x39,
  mt: 0x3a, ga: 0x3c, bn: 0x45, gl: 0x56,
};

/** Full LCIDs that pick a regional variant; anything else falls back to `DEFAULT_VARIANT`. */
const REGIONAL = {
  0x0809: 'en-GB', 0x1809: 'en-GB', 0x0c09: 'en-GB', 0x1409: 'en-GB', 0x1c09: 'en-GB', 0x4009: 'en-GB',
  0x0816: 'pt-PT',
  0x0404: 'zh-Hant', 0x0c04: 'zh-Hant', 0x1404: 'zh-Hant',
};
const DEFAULT_VARIANT = { 0x09: 'en-US', 0x16: 'pt-BR', 0x04: 'zh-Hans' };

/**
 * Escapes a string for an NSIS double-quoted literal.
 *
 * @param {string} text
 * @returns {string}
 */
function nsisString(text) {
  return `"${text.replace(/\$/g, '$$$$').replace(/"/g, '$\\"')}"`;
}

/**
 * Writes the NSIS include file and returns its path, for electron-builder's `nsis.include`.
 *
 * @param {string} outputDir - Where to write `installer.nsh`.
 * @returns {string}
 */
function writeInstallerScript(outputDir) {
  const { languages } = JSON.parse(fs.readFileSync(path.join(LOCALES, 'languages.json'), 'utf8'));
  const chooseText = Object.fromEntries(languages.map(({ code }) => [
    code,
    JSON.parse(fs.readFileSync(path.join(LOCALES, `${code}.json`), 'utf8'))['language.choose'],
  ]));

  const caseLines = (map) => Object.entries(map)
    .map(([id, code]) => `      \${Case} ${Number(id)}\n        StrCpy $R1 "${code}"\n        \${Break}`)
    .join('\n');

  const promptLines = languages
    .map(({ code }) => `    \${Case} "${code}"\n      StrCpy $R2 ${nsisString(chooseText[code])}\n      \${Break}`)
    .join('\n');

  const entries = languages.map(({ code, name }) => `${nsisString(name)} "${code}"`).join(' ');

  const script = `; Generated by build/installer-language.js from the locales folder. Do not edit by hand.
; Adds a language menu to the Salchi installer and passes the choice on to the app.

!include "LogicLib.nsh"

; The uninstaller is built from the same script but never asks for a language.
!ifndef BUILD_UNINSTALLER
  Var SalchiLanguage
!endif

!macro customInit
  StrCpy $SalchiLanguage ""
  \${IfNot} \${Silent}
    ; Guess the language from Windows' display language.
    System::Call 'kernel32::GetUserDefaultUILanguage() i .R0'
    IntOp $R3 $R0 & 0x3FF
    StrCpy $R1 "en-US"
    \${Switch} $R0
${caseLines(REGIONAL)}
      \${Default}
        \${Switch} $R3
${caseLines({ ...Object.fromEntries(Object.entries(PRIMARY).map(([code, id]) => [id, code])), ...DEFAULT_VARIANT })}
        \${EndSwitch}
    \${EndSwitch}

    ; The menu's own text, in the guessed language.
    \${Switch} $R1
${promptLines}
    \${EndSwitch}

    ; LangDLL preselects the entry whose value equals $LANGUAGE, so borrow it for a moment.
    StrCpy $R4 $LANGUAGE
    StrCpy $LANGUAGE $R1
    LangDLL::LangDialog "Salchi" "$R2" A ${entries} ""
    Pop $SalchiLanguage
    StrCpy $LANGUAGE $R4
    \${If} $SalchiLanguage == "cancel"
      Quit
    \${EndIf}
  \${EndIf}
!macroend

!macro customInstall
  \${If} $SalchiLanguage != ""
    FileOpen $R5 "$INSTDIR\\resources\\install-language.txt" w
    FileWrite $R5 $SalchiLanguage
    FileClose $R5
  \${EndIf}
!macroend
`;

  fs.mkdirSync(outputDir, { recursive: true });
  const file = path.join(outputDir, 'installer.nsh');
  fs.writeFileSync(file, script);
  return file;
}

module.exports = { writeInstallerScript };
